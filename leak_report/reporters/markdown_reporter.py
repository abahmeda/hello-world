from ..models import LeakReport

_SEVERITY_BADGES = {
    "critical": "🔴 Critical",
    "high":     "🟠 High",
    "medium":   "🟡 Medium",
    "low":      "🟢 Low",
}

_STATUS_ICONS = {
    "pending":     "⬜",
    "in-progress": "🔄",
    "completed":   "✅",
    "deferred":    "⏸️",
}


def generate_markdown(report: LeakReport) -> str:
    inc = report.incident
    lines: list[str] = []

    lines.append("# Leak Investigation Report")
    lines.append("")
    lines.append(f"| Field | Value |")
    lines.append(f"|-------|-------|")
    lines.append(f"| Generated | {report.generated_at.strftime('%Y-%m-%d %H:%M:%S')} |")
    lines.append(f"| Prepared by | {report.generated_by} |")
    lines.append("")

    lines.append("## 1. Incident Overview")
    lines.append("")
    lines.append(f"| Field | Value |")
    lines.append(f"|-------|-------|")
    lines.append(f"| **Incident ID** | `{inc.incident_id}` |")
    lines.append(f"| **Title** | {inc.title} |")
    lines.append(f"| **Type** | {inc.leak_type.title()} |")
    lines.append(f"| **Severity** | {_SEVERITY_BADGES.get(inc.severity, inc.severity)} |")
    lines.append(f"| **Detected** | {inc.detected_at.strftime('%Y-%m-%d %H:%M')} |")
    lines.append(f"| **Reported By** | {inc.reported_by} |")
    lines.append(f"| **Location** | {inc.location} |")
    lines.append("")
    lines.append("**Description:**")
    lines.append("")
    lines.append(inc.description)
    lines.append("")
    if inc.affected_systems:
        lines.append("**Affected Systems:**")
        lines.append("")
        for s in inc.affected_systems:
            lines.append(f"- {s}")
        lines.append("")

    lines.append("## 2. Executive Summary")
    lines.append("")
    lines.append(report.executive_summary)
    lines.append("")

    lines.append("## 3. Timeline of Events")
    lines.append("")
    if report.timeline:
        lines.append("| Timestamp | Event | Actor |")
        lines.append("|-----------|-------|-------|")
        for evt in sorted(report.timeline, key=lambda e: e.timestamp):
            ts = evt.timestamp.strftime("%Y-%m-%d %H:%M")
            lines.append(f"| {ts} | {evt.event} | {evt.actor} |")
    else:
        lines.append("_No timeline events recorded._")
    lines.append("")

    lines.append("## 4. Root Cause Analysis")
    lines.append("")
    lines.append(report.root_cause)
    lines.append("")

    lines.append("## 5. Impact Assessment")
    lines.append("")
    lines.append(report.impact_assessment)
    lines.append("")

    lines.append("## 6. Findings")
    lines.append("")
    if report.findings:
        for i, f in enumerate(report.findings, 1):
            badge = _SEVERITY_BADGES.get(f.severity, f.severity)
            lines.append(f"### Finding #{i}: {f.category} ({badge})")
            lines.append("")
            lines.append(f"**Description:** {f.description}")
            lines.append("")
            lines.append(f"**Evidence:** {f.evidence}")
            lines.append("")
    else:
        lines.append("_No findings recorded._")
        lines.append("")

    lines.append("## 7. Remediation Steps")
    lines.append("")
    if report.remediation_steps:
        lines.append("| # | Status | Action | Owner | Deadline |")
        lines.append("|---|--------|--------|-------|----------|")
        for step in sorted(report.remediation_steps, key=lambda s: s.priority):
            icon = _STATUS_ICONS.get(step.status, step.status)
            lines.append(f"| {step.priority} | {icon} {step.status.title()} | {step.action} | {step.owner} | {step.deadline} |")
    else:
        lines.append("_No remediation steps recorded._")
    lines.append("")

    lines.append("## 8. Recommendations")
    lines.append("")
    if report.recommendations:
        for rec in report.recommendations:
            lines.append(f"- {rec}")
    else:
        lines.append("_No recommendations recorded._")
    lines.append("")

    lines.append("---")
    lines.append(f"_Report generated by {report.generated_by} on {report.generated_at.strftime('%Y-%m-%d %H:%M:%S')}_")

    return "\n".join(lines)
